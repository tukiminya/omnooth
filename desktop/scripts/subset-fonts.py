"""Regenerate optional initial-UI font subsets from the bundled full WOFF2 files.

Requires fonttools[woff]. Full glyph coverage remains available on demand.
Run from any directory after changing the interface's text.
"""
from pathlib import Path
import json
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
fonts = root / 'public' / 'fonts'
text = ''.join(path.read_text() for path in (root / 'src').rglob('*')
               if path.suffix in ('.ts', '.tsx'))
ui = {ord(char) for char in text} | set(range(0x20, 0x7f))


def unicode_ranges(points, excluded=frozenset()):
    ranges = []
    for point in sorted(points):
        # Small cmap holes need not become thousands of CSS ranges. A face still
        # falls back normally when the actual font has no glyph for a codepoint.
        if (ranges and point - ranges[-1][1] <= 128
                and not any(ranges[-1][1] < value < point for value in excluded)):
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ','.join(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}'
                    for start, end in ranges)


rules, report = [], []
for filename, family, weight in [
    ('LINESeedJP-Regular', 'LINE Seed JP', 400),
    ('LINESeedJP-Bold', 'LINE Seed JP', 700),
    ('GenInterfaceJP-Regular', 'Gen Interface JP', 400),
    ('GenInterfaceJP-Medium', 'Gen Interface JP', 500),
]:
    source = fonts / (filename + '.woff2')
    font = TTFont(source)
    available = set(font.getBestCmap())
    initial, rest = available & ui, available - ui
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=initial)
    subsetter.subset(font)
    target = fonts / (filename + '.ui.woff2')
    font.flavor = 'woff2'
    font.save(target)
    for suffix, points in [('.woff2', rest), ('.ui.woff2', initial)]:
        rules.append("@font-face {\n"
                     f"  font-family: '{family}'; font-weight: {weight};\n"
                     "  font-style: normal; font-display: swap;\n"
                     f"  src: url('/fonts/{filename}{suffix}') format('woff2');\n"
                     f"  unicode-range: {unicode_ranges(points, initial if suffix == '.woff2' else rest)};\n"
                     "}\n")
    report.append({'font': filename, 'fullBytes': source.stat().st_size,
                   'initialUiBytes': target.stat().st_size,
                   'initialGlyphs': len(initial)})

rules.append("@font-face {\n"
             "  font-family: 'JetBrains Mono'; font-weight: 400;\n"
             "  font-style: normal; font-display: swap;\n"
             "  src: url('/fonts/JetBrainsMono-Regular.woff2') format('woff2');\n"
             "}\n")
(root / 'src' / 'fonts.css').write_text('/* Generated by scripts/subset-fonts.py. */\n' + '\n'.join(rules))
(fonts / 'subsets.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report))
